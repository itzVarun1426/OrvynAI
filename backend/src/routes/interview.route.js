import express from 'express';
import authMiddleware from '../middlewares/auth.middleware.js';
import interviewController from '../controllers/interview.controller.js';
import upload from '../middlewares/file.middleware.js';

const router = express.Router();

/**
 * @route POST /api/interview
 * @description generate the candidate profile, skill gaps, interview plan, and initial questions
 * @access private
 */
router.post('/', authMiddleware.authUser, upload.single('resume'), interviewController.generateInterviewReportController);

/**
 * @route GET /api/interview/report/:interviewId
 * @description get interview report on the basis of interviewId
 * @access private
 */
router.get('/report/:interviewId', authMiddleware.authUser, interviewController.getInterviewByIdController);

/**
 * @route GET /api/interview/
 * @description get all the reports generated by logined user 
 * @access private
 */
router.get('/', authMiddleware.authUser, interviewController.getAllInterviewReportByUserId);

/**
 * @route DELETE /api/interview/:interviewId
 * @description delete an interview report
 * @access private
 */
router.delete('/:interviewId', authMiddleware.authUser, interviewController.deleteInterviewReportController);

/**
 * @route POST /api/interview/:interviewId/answer
 * @description submit a single question answer for adaptive evaluation
 * @access private
 */
router.post('/:interviewId/answer', authMiddleware.authUser, upload.single('audio'), interviewController.submitAnswerController);

/**
 * @route POST /api/interview/:interviewId/next-question
 * @description get next dynamic adaptive question responding to candidate's prior performance
 * @access private
 */
router.post('/:interviewId/next-question', authMiddleware.authUser, interviewController.getNextAdaptiveQuestionController);

/**
 * @route POST /api/interview/:interviewId/complete
 * @description mark the interview as completed and synthesize visual dashboard metrics
 * @access private
 */
router.post('/:interviewId/complete', authMiddleware.authUser, interviewController.completeInterviewController);

/**
 * @route POST /api/interview/:interviewId/retry-weak
 * @description generate a focused mini-interview targeting diagnosed weak areas
 * @access private
 */
router.post('/:interviewId/retry-weak', authMiddleware.authUser, interviewController.retryWeakAreasController);

export default router;
